let clock;
let counter = 0;
beforeAll(async () => {
    LiteGraph.initialize();
    await LiteGraph.LibraryManager.ready;
    /** a value from outside state: a new number on every run */
    const reader = (execution) => class {
        static def = execution ? { execution } : undefined;
        constructor() { this.addOutput('v', 'number'); this.runs = 0; }
        onExecute() { this.runs++; this.setOutputData(0, ++counter); }
    };
    LiteGraph.registerNodeType('cs/volatile', reader({ pure: 'volatile' }));
    LiteGraph.registerNodeType('cs/undeclared', reader(null));
    /** deterministic: its output is its property k */
    LiteGraph.registerNodeType('cs/det', class {
        static def = { execution: { pure: true } };
        constructor() { this.addInput('a', 'number'); this.addOutput('v', 'number'); this.properties = { k: 1 }; this.runs = 0; }
        onExecute() { this.runs++; this.setOutputData(0, this.properties.k + (this.getInputData(0) ?? 0)); }
    });
    /** declared pure but reads outside state: regenerated by its refresh input only */
    LiteGraph.registerNodeType('cs/stamp', class {
        static def = { execution: { pure: true } };
        constructor() { this.addOutput('v', 'number'); this.runs = 0; }
        onExecute() { this.runs++; this.setOutputData(0, ++counter); }
    });
    LiteGraph.registerNodeType('cs/plus', class {
        static def = { execution: { pure: true } };
        constructor() { this.addInput('a', 'number'); this.addOutput('v', 'number'); this.runs = 0; }
        onExecute() { this.runs++; this.setOutputData(0, (this.getInputData(0) ?? 0) + 100); }
    });
    LiteGraph.registerNodeType('cs/src', class { constructor() { this.addOutput('go', LiteGraph.EVENT); } });
    /** records its two data inputs and the call id on each action */
    LiteGraph.registerNodeType('cs/rec', class {
        constructor() { this.addInput('in', LiteGraph.ACTION); this.addInput('v', 0); this.addInput('w', 0); this.log = []; this.calls = []; }
        onAction(_a, _p, options) { this.log.push([this.getInputData(1), this.getInputData(2)]); this.calls.push([options?.action_call, ExecutionEngine.scopeId]); }
    });
    /** fires its event output twice in one action */
    LiteGraph.registerNodeType('cs/twice', class {
        constructor() { this.addInput('in', LiteGraph.ACTION); this.addOutput('out', LiteGraph.EVENT); }
        onAction() { this.triggerSlot(0); this.triggerSlot(0); }
    });
    LiteGraph.registerNodeType('cs/sink', class {
        constructor() { this.addInput('v', 0); this.addOutput('v', 0); this.seen = []; }
        onExecute() { const v = this.getInputData(0, true); this.seen.push(v); this.setOutputData(0, v); }
    });
    LiteGraph.registerNodeType('cs/below', class {
        constructor() { this.addInput('v', 'number'); this.addOutput('ok', 'boolean'); }
        onExecute() { this.setOutputData(0, (this.getInputData(0) ?? 0) % 4 !== 0); }
    });
});
beforeEach(() => {
    clock = 1000;
    counter = 0;
    jest.spyOn(LiteGraph, 'getTime').mockImplementation(() => clock);
    for (const level of ['info', 'debug', 'log', 'warn']) jest.spyOn(console, level).mockImplementation(() => {});
    jest.spyOn(LiteGraph, 'log_warn').mockImplementation(() => {});
});
afterEach(() => { jest.restoreAllMocks(); NodeFunction._depth = 0; });

function graph(model = 'ancestors') {
    const g = new LGraph();
    g.config.execution = model;
    return g;
}
function make(g, type, props = {}, mode) {
    const node = LiteGraph.createNode(type);
    Object.assign(node.properties, props);
    g.add(node);
    if (mode !== undefined) node.mode = mode;
    return node;
}
function step(g) { clock += 10; g.runStep(1); }

/** src -> FOR(nElements n) -do-> recA, recB; reader -> both */
function forLoop(model, readerType, n = 3) {
    const g = graph(model);
    const src = make(g, 'cs/src');
    const count = make(g, 'basic/const', { value: n });
    const loop = make(g, 'logic/CycleFOR');
    const reader = make(g, readerType, {}, LiteGraph.ON_REQUEST);
    const recA = make(g, 'cs/rec'), recB = make(g, 'cs/rec');
    count.connect(0, loop, 1);
    src.connect(0, loop, 2);
    loop.connect(0, recA, 0); loop.connect(0, recB, 0);
    reader.connect(0, recA, 1); reader.connect(0, recA, 2); reader.connect(0, recB, 1);
    return { g, src, loop, reader, recA, recB };
}

describe.each(['ancestors', 'step', 'event'])('model %s', (model) => {
    /** a first step gives ALWAYS constants their value; deferred actions run in the next step */
    const fire = (g, src) => { step(g); src.triggerSlot(0); if (model === 'step') step(g); };
    test('research 1 / finding 1: FOR x3, a volatile reader is fresh per iteration and shared within one', () => {
        const { g, src, reader, recA, recB } = forLoop(model, 'cs/volatile');
        fire(g, src);
        expect(recA.log).toHaveLength(3);
        expect(new Set(recA.log.map(([v]) => v)).size).toBe(3);
        for (let i = 0; i < 3; i++) {
            expect(recA.log[i][0]).toBe(recA.log[i][1]);
            expect(recB.log[i][0]).toBe(recA.log[i][0]);
        }
        expect(reader.runs).toBe(3);
    });

    test('finding 1: an undeclared ON_REQUEST reader is fresh per iteration too', () => {
        const { g, src, reader, recA } = forLoop(model, 'cs/undeclared');
        fire(g, src);
        expect(new Set(recA.log.map(([v]) => v)).size).toBe(3);
        expect(reader.runs).toBe(3);
    });

    test('research 2 / finding 1: Sequence outputs reading one volatile node get one value each', () => {
        const g = graph(model);
        const src = make(g, 'cs/src');
        const seq = make(g, 'events/sequence');
        const reader = make(g, 'cs/volatile', {}, LiteGraph.ON_REQUEST);
        const recA = make(g, 'cs/rec'), recB = make(g, 'cs/rec');
        src.connect(0, seq, 0);
        seq.connect(0, recA, 0); seq.connect(1, recB, 0);
        reader.connect(0, recA, 1); reader.connect(0, recB, 1);
        fire(g, src);
        expect(recA.log).toHaveLength(1);
        expect(recB.log).toHaveLength(1);
        expect(recA.log[0][0]).not.toBe(recB.log[0][0]);
        expect(reader.runs).toBe(2);
    });

    test('research 6 / finding 4: graph/function called twice in one call runs its inner volatile node once per call', () => {
        const g = graph(model);
        const reader = make(g, 'cs/volatile', {}, LiteGraph.ON_REQUEST);
        const pass = make(g, 'cs/sink', {}, LiteGraph.ALWAYS);
        const out = make(g, 'cs/sink', {}, LiteGraph.NEVER);
        reader.connect(0, pass, 0); pass.connect(0, out, 0);
        const sub = g.convertToSubgraph([reader, pass]);
        g.serialize();
        const fn = make(g, 'graph/function');
        expect(fn.setDefinition(sub.properties.subgraph_id)).toBe(true);
        const src = make(g, 'cs/src');
        const twice = make(g, 'cs/twice');
        const rec = make(g, 'cs/rec');
        const valueSlot = fn.outputs.findIndex((o) => o.type !== LiteGraph.EVENT);
        src.connect(0, twice, 0);
        twice.connect(0, fn, fn.findInputSlot('call'));
        fn.connect(fn.findOutputSlot('done'), rec, 0);
        fn.connect(valueSlot, rec, 1);
        const inner = fn.subgraph._nodes.find((n) => n.type === 'cs/volatile');
        fire(g, src);
        expect(inner.runs).toBe(2);
        expect(rec.log).toHaveLength(2);
        expect(rec.log[0][0]).not.toBe(rec.log[1][0]);
    });

    test('finding 3: one call id; the action_call is the scope id, Sequence outputs get child ids', () => {
        const g = graph(model);
        const src = make(g, 'cs/src');
        const seq = make(g, 'events/sequence');
        const recA = make(g, 'cs/rec'), recB = make(g, 'cs/rec');
        src.connect(0, seq, 0);
        seq.connect(0, recA, 0); seq.connect(1, recB, 0);
        step(g);
        const random = jest.spyOn(Math, 'random');
        src.triggerSlot(0);
        expect(random).not.toHaveBeenCalled();
        const [[callA, scopeA]] = recA.calls;
        const [[callB, scopeB]] = recB.calls;
        expect(callA).toBe(scopeA);
        expect(callB).toBe(scopeB);
        expect(scopeA).toMatch(new RegExp(`^call_\\d+/${seq.id}\\.s0$`));
        expect(scopeB).toMatch(new RegExp(`^call_\\d+/${seq.id}\\.s1$`));
        expect(scopeA.split('/')[0]).toBe(scopeB.split('/')[0]);
        expect(ExecutionEngine.scopeId).toBeNull();
    });
});

describe('ancestors', () => {
    test('research 3: a deterministic pure node read in five steps with unchanged inputs runs once', () => {
        const g = graph();
        const det = make(g, 'cs/det', {}, LiteGraph.ON_REQUEST);
        const sink = make(g, 'cs/sink', {}, LiteGraph.ALWAYS);
        det.connect(0, sink, 0);
        for (let i = 0; i < 5; i++) step(g);
        expect(det.runs).toBe(1);
        expect(sink.seen).toEqual([1, 1, 1, 1, 1]);
        det.setProperty('k', 2);
        step(g);
        expect(det.runs).toBe(2);
        expect(sink.seen.at(-1)).toBe(2);
    });

    test('a rewired deterministic node runs again (no stale memo)', () => {
        const g = graph();
        const det = make(g, 'cs/det', {}, LiteGraph.ON_REQUEST);
        const sink = make(g, 'cs/sink', {}, LiteGraph.ALWAYS);
        det.connect(0, sink, 0);
        step(g); step(g);
        const other = make(g, 'cs/det', { k: 10 }, LiteGraph.ON_REQUEST);
        other.connect(0, det, 0);
        step(g);
        expect(sink.seen.at(-1)).toBe(11);
        det.disconnectInput(0);
        step(g);
        expect(sink.seen.at(-1)).toBe(1);
    });

    test.each(['cs/det', 'cs/volatile'])('research 4 / finding 2: setProperty inside one call is seen by the next read (%s)', (type) => {
        const g = graph();
        const node = make(g, type, {}, LiteGraph.ON_REQUEST);
        const reads = [];
        LiteGraph.registerNodeType('cs/editor', class {
            constructor() { this.addInput('in', LiteGraph.ACTION); this.addInput('v', 0); }
            onAction() {
                reads.push(this.getInputData(1, true));
                const origin = this.getInputNode(1);
                origin.setProperty('k', (origin.properties.k ?? 0) + 5);
                reads.push(this.getInputData(1, true));
            }
        });
        const editor = make(g, 'cs/editor');
        const src = make(g, 'cs/src');
        src.connect(0, editor, 0);
        node.connect(0, editor, 1);
        src.triggerSlot(0);
        expect(node.runs).toBe(2);
        expect(reads[1]).not.toBe(reads[0]);
    });

    test('research 5: the refresh action re-runs the node and restamps its outputs; pure consumers follow', () => {
        const g = graph();
        const stamp = make(g, 'cs/stamp', {}, LiteGraph.ON_REQUEST);
        const plus = make(g, 'cs/plus', {}, LiteGraph.ON_REQUEST);
        const sink = make(g, 'cs/sink', {}, LiteGraph.ALWAYS);
        stamp.connect(0, plus, 0); plus.connect(0, sink, 0);
        const slot = ExecutionEngine.addRefreshInput(stamp);
        expect(stamp.inputs[slot]).toMatchObject({ name: 'refresh', type: LiteGraph.ACTION, refresh: true });
        expect(ExecutionEngine.addRefreshInput(stamp)).toBe(slot); // only one
        step(g); step(g);
        expect(sink.seen).toEqual([101, 101]);
        expect(stamp.runs).toBe(1);
        const src = make(g, 'cs/src');
        src.connect(0, stamp, slot);
        src.triggerSlot(0);
        expect(stamp.runs).toBe(2);
        step(g);
        expect(sink.seen.at(-1)).toBe(102);
        expect(plus.runs).toBe(2);
        stamp.actionDo('refresh'); // a host call works too
        step(g);
        expect(sink.seen.at(-1)).toBe(103);
    });

    test('the Inputs menu offers refresh on ON_REQUEST nodes outside legacy', () => {
        const g = graph();
        const det = make(g, 'cs/det', {}, LiteGraph.ON_REQUEST);
        const always = make(g, 'cs/det', {}, LiteGraph.ALWAYS);
        expect(ExecutionEngine.offersRefresh(det)).toBe(true);
        expect(ExecutionEngine.offersRefresh(always)).toBe(false);
        ExecutionEngine.addRefreshInput(det);
        expect(ExecutionEngine.offersRefresh(det)).toBe(false);
        const legacy = graph('legacy');
        expect(ExecutionEngine.offersRefresh(make(legacy, 'cs/det', {}, LiteGraph.ON_REQUEST))).toBe(false);
    });

    test('finding 1: WHILE re-evaluates a volatile condition in each iteration', () => {
        const g = graph();
        const src = make(g, 'cs/src');
        const loop = make(g, 'logic/CycleWHILE', { cycleLimit: 50 });
        const reader = make(g, 'cs/volatile', {}, LiteGraph.ON_REQUEST);
        const cond = make(g, 'cs/below', {}, LiteGraph.ON_REQUEST);
        const rec = make(g, 'cs/rec');
        reader.connect(0, cond, 0); cond.connect(0, loop, 1);
        src.connect(0, loop, 0);
        loop.connect(0, rec, 0);
        reader.connect(0, rec, 1);
        src.triggerSlot(0);
        // the reader counts 1, 2, 3, ... and the condition is false at 4: it is pulled per iteration
        expect(rec.log.length).toBeGreaterThan(0);
        expect(rec.log.length).toBeLessThan(50);
    });

    test('declarations: math/rand, math/formula and basic/time are volatile and start ON_REQUEST', () => {
        expect(ExecutionEngine.declarationOf('basic/variable')).toBeNull(); // a setter too: not pure
        for (const type of ['math/rand', 'math/formula', 'basic/time']) {
            expect(ExecutionEngine.declarationOf(type)).toMatchObject({ pure: true, volatile: true });
        }
        expect(ExecutionEngine.declarationOf('math/operation')).toMatchObject({ pure: true, volatile: false });
        const g = graph();
        expect(make(g, 'math/rand').mode).toBe(LiteGraph.ON_REQUEST);
    });

    test('math/rand under ON_REQUEST gives a new value per FOR iteration', () => {
        const { src, recA } = forLoop('ancestors', 'math/rand');
        src.triggerSlot(0);
        expect(new Set(recA.log.map(([v]) => v)).size).toBe(3);
    });

    test('FLW-14: checkExecution warns when a volatile node feeds a loop input', () => {
        const g = graph();
        const reader = make(g, 'cs/volatile', {}, LiteGraph.ON_REQUEST);
        const plus = make(g, 'cs/plus', {}, LiteGraph.ON_REQUEST);
        const loop = make(g, 'logic/CycleFOR');
        const rec = make(g, 'cs/rec');
        loop.connect(0, rec, 0);
        reader.connect(0, plus, 0); plus.connect(0, loop, 1);
        const issues = g.checkExecution().issues.filter((i) => i.code === 'volatile-loop-input');
        expect(issues).toHaveLength(1);
        expect(issues[0].node).toBe(loop);
        expect(issues[0].message).toMatch(/nElements/);
        plus.disconnectInput(0);
        expect(g.checkExecution().issues.filter((i) => i.code === 'volatile-loop-input')).toHaveLength(0);
    });
});

describe('legacy', () => {
    test('Sequence keeps its own call ids (and its Math.random use) under legacy', () => {
        const g = graph('legacy');
        const src = make(g, 'cs/src');
        const seq = make(g, 'events/sequence');
        const recA = make(g, 'cs/rec');
        src.connect(0, seq, 0);
        seq.connect(0, recA, 0);
        const random = jest.spyOn(Math, 'random');
        src.triggerSlot(0);
        if (LiteGraph.use_deferred_actions) step(g);
        expect(random).toHaveBeenCalled();
        expect(recA.calls[0][0]).toMatch(/_seq_0_\d+$/);
    });
});
